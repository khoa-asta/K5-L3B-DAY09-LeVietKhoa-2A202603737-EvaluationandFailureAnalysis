"""Generate M3 grader evidence with the supplied eval harness and public fixtures.

Run from src/: python -m scripts.build_m3_validation
Reports are generated by lab9.eval, never edited by hand. The isolated reply
fault is registered in this process only; supplied variants stay unchanged.
"""
from __future__ import annotations

import json
from pathlib import Path

from lab8.shapes import SHAPES
from lab9.eval import load_spec, main as eval_main
from lab9.evalset import sha12
from lab9.graders import GRADERS
from lab9.variant_agent import make_shape


OUTPUT = Path("../docs/evidence/m3_grader_validation.json")


def main() -> None:
    spec = load_spec()
    fault = "m3_isolated_misreport"
    SHAPES[fault] = make_shape(fault, {"no_override", "misreport"})
    reports = {}
    try:
        for name in ("fixed", "seeded_regression", "honest_refactor", fault):
            path = Path(f"reports/m3_{name}.json")
            if eval_main(["--shape", name, "--out", str(path)]) != 0:
                raise RuntimeError(f"Evaluation failed: {name}")
            reports[name] = json.loads(path.read_text(encoding="utf-8"))
    finally:
        SHAPES.pop(fault, None)

    # Same definition as lab9.mutation.detect: exclude pass_rate so detection
    # requires another grader to explain why a Lab 8 trial failed.
    bad_value = {m["id"]: "max" in (m.get("threshold") or {}) for m in spec["metrics"]
                 if m["id"] in GRADERS and m["id"] != "pass_rate"}

    def flagged(row):
        return any(row.get(metric) is bad for metric, bad in bad_value.items())

    broken = [r for r in reports["seeded_regression"]["rows"] if r["pass_rate"] is False]
    controls = reports["fixed"]["rows"]
    honest = reports["honest_refactor"]["rows"]
    detected = sum(flagged(r) for r in broken)
    false_alarms = sum(flagged(r) for r in controls)
    fm08_rows = [r for r in reports[fault]["rows"] if r["reply_amount_correct"] is False]
    detection = detected / len(broken) if broken else 0.0
    false_alarm_rate = false_alarms / len(controls)
    result = {
        "generator": "python -m scripts.build_m3_validation",
        "metric_spec_version": spec["metric_spec_version"],
        "spec_sha12": sha12(Path("config/metric_spec.yaml")),
        "graders_sha12": sha12(Path("lab9/graders.py")),
        "detection": {"detected": detected, "failing_trials": len(broken), "rate": detection,
                      "target_min": 0.8},
        "fixed_false_alarms": {"flagged": false_alarms, "trials": len(controls),
                               "rate": false_alarm_rate, "target_max": 0.1},
        "honest_refactor_false_alarms": {"flagged": sum(flagged(r) for r in honest), "trials": len(honest)},
        "isolated_fm08": {"detected": len(fm08_rows),
                          "also_passed_lab8": sum(r["pass_rate"] is True for r in fm08_rows),
                          "affected_items": sorted({r["item_id"] for r in fm08_rows})},
        "passed": detection >= 0.8 and false_alarm_rate <= 0.1,
        "reports": reports,
    }
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(json.dumps(result, ensure_ascii=False, indent=2, allow_nan=False) + "\n", encoding="utf-8")
    print(f"M3: detected {detected}/{len(broken)} ({detection:.2%}), "
          f"false alarms {false_alarms}/{len(controls)} ({false_alarm_rate:.2%})")
    print(f"FM-08: {len(fm08_rows)} reply mismatches detected despite Lab 8 PASS")
    print(f"wrote {OUTPUT}")
    if not result["passed"]:
        raise SystemExit(1)


if __name__ == "__main__":
    main()
